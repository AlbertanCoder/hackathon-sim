// Opens the live GitHub Pages copy of Hackathon Sim in headless Edge and plays a little of it.
import { spawn } from 'node:child_process';
import { mkdtempSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const URL = 'https://albertancoder.github.io/hackathon-sim/';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const prof = mkdtempSync(join(tmpdir(), 'hsim-live-'));
const edge = spawn('C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', ['--headless=new', '--disable-gpu', '--no-first-run', `--user-data-dir=${prof}`, '--remote-debugging-port=0', '--window-size=400,900', 'about:blank'], { stdio: 'ignore' });
const pf = join(prof, 'DevToolsActivePort');
for (let i = 0; i < 100 && !existsSync(pf); i++) await sleep(100);
await sleep(200);
const port = readFileSync(pf, 'utf8').split('\n')[0].trim();
const t = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find(x => x.type === 'page');
const ws = new WebSocket(t.webSocketDebuggerUrl); await new Promise(r => ws.addEventListener('open', r));
let id = 0; const w = new Map(), errors = [];
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id && w.has(m.id)) { w.get(m.id)(m); w.delete(m.id); }
  if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text); });
const cdp = (method, params = {}) => new Promise(r => { const i = ++id; w.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
const js = async x => { const r = await cdp('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result.exceptionDetails) errors.push(x + ' -> ' + JSON.stringify(r.result.exceptionDetails)); return r.result.result?.value; };
let bad = 0; const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) bad++; };
await cdp('Runtime.enable'); await cdp('Page.enable');
await cdp('Emulation.setDeviceMetricsOverride', { width: 400, height: 900, deviceScaleFactor: 1, mobile: false });
await cdp('Page.navigate', { url: URL + '?t=' + Date.now() }); await sleep(3000);
ok(await js(`location.href.startsWith('${URL}')`), 'the live page opens at ' + URL);
ok(await js(`typeof window.__sim === 'object' && document.title.length > 0`), 'the game loaded: ' + await js('document.title'));
ok(await js(`window.__sim.lxState().screen === 'home'`), 'it starts on Home');
ok(await js(`document.documentElement.scrollWidth <= 401`), 'Home has no sideways scroll at phone width');
await js(`window.__sim.lesson('py-imports')`); await sleep(200);
await js(`window.__sim.lxNext()`); await sleep(150);
const st = await js(`window.__sim.lxState()`);
ok(st.id === 'py-imports' && st.step === 'STEP 2 OF 7', 'a lesson opens and moves to step 2: ' + st.step);
const right = (await js(`window.__sim.course()`)).flatMap(m => m.lessons).find(l => l.id === 'py-imports').steps[1].right;
await js(`window.__sim.lxAnswer(${right})`); await sleep(150);
ok((await js(`window.__sim.lxState()`)).passed, 'the right answer passes');
ok(await js(`document.documentElement.scrollWidth <= 401`), 'that step has no sideways scroll at phone width (the fixed one)');
ok(await js(`JSON.parse(localStorage.getItem('hsim-learn')).at.id === 'py-imports'`), 'progress saves in the browser');
ok(!errors.length, 'no script errors' + (errors.length ? ': ' + errors.join(' | ') : ''));
console.log(bad ? 'live: ' + bad + ' failed' : 'live: all ok');
edge.kill(); process.exit(bad ? 1 : 0);
