// Puts the level files (levels/*.js) into index.html. Each file defines its lesson constants and ends with one or more
// lines that start with /*MODULE*/ (the entry for the COURSE list). The constants go into a generated block just above
// "const COURSE = [", the module entries go into the COURSE list just after the Python module. Safe to run again: it replaces
// whatever was inserted last time. Edit the files in levels/, never the generated block.
// Run: node check/inject-levels.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const idx = join(root, 'index.html');
let s = readFileSync(idx, 'utf8');
const lfBefore = s.split('\n').length - 1 - (s.match(/\r\n/g) || []).length;
const crlf = t => t.replace(/\r\n/g, '\n').replace(/\n/g, '\r\n');
const files = readdirSync(join(root, 'levels')).filter(f => /^l\d+.*\.js$/.test(f)).sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));
let consts = '', mods = [];
for (const f of files) {
  const lines = readFileSync(join(root, 'levels', f), 'utf8').replace(/\r\n/g, '\n').split('\n');
  const keep = [];
  for (const l of lines) { if (l.startsWith('/*MODULE*/')) mods.push(l.slice('/*MODULE*/'.length).trim()); else keep.push(l); }
  consts += '// ----- levels/' + f + ' -----\n' + keep.join('\n').replace(/\n+$/, '') + '\n';
}
const B1 = '// ===== LEVELS 4 TO 12: generated by check/inject-levels.mjs from levels/*.js. Edit those files, not this block. =====';
const B2 = '// ===== END GENERATED LEVELS =====';
const M1 = '  /*LEVELS-MODULES-BEGIN*/', M2 = '  /*LEVELS-MODULES-END*/';
// the constants block
const block = crlf(B1 + '\n' + consts + B2 + '\n');
if (s.includes(B1)) {
  const a = s.indexOf(B1), b = s.indexOf(B2) + B2.length;
  s = s.slice(0, a) + block.replace(/\r\n$/, '') + s.slice(b);
} else {
  const anchor = '// The course. Lessons without steps show as "coming next".';
  const i = s.indexOf(anchor); if (i < 0) throw new Error('anchor for the constants block not found');
  s = s.slice(0, i) + block + s.slice(i);
}
// the module entries, inside COURSE just after the Python module
const entries = crlf(M1 + '\n' + mods.map(m => '  ' + m).join('\n') + (mods.length ? '\n' : '') + M2);
if (s.includes(M1)) {
  const a = s.indexOf(M1), b = s.indexOf(M2) + M2.length;
  s = s.slice(0, a) + entries + s.slice(b);
} else {
  const re = /(\{id:'python', name:'[^\r\n]*\], tests:\[\]\},)(\r\n)/;
  if (!re.test(s)) throw new Error('the Python module line was not found');
  s = s.replace(re, (m, a, nl) => a + nl + entries + nl);
}
const lfAfter = s.split('\n').length - 1 - (s.match(/\r\n/g) || []).length;
if (lfAfter !== lfBefore) throw new Error('LF-only line count changed: ' + lfBefore + ' -> ' + lfAfter);
writeFileSync(idx, s);
console.log('injected', files.length, 'level files,', mods.length, 'modules; LF-only lines', lfAfter);
